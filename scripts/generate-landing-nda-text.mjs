/**
 * Precomputes the landing page's NDA text (segments + real counts) from the standard NDA template.
 * Run: node scripts/generate-landing-nda-text.mjs   (Node 22.18+ / 23.6+, uses built-in type stripping)
 * Output: src/lib/landing/ndaText.generated.ts (checked in; ndaText.test.ts fails when it is stale)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildNdaText } from '../src/lib/landing/ndaText.ts';
import { SAMPLE_DEAL } from '../src/lib/landing/sampleDeal.ts';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const templatePath = path.join(root, 'templates', 'professional_mutual_nda_v1.hbs');
const outPath = path.join(root, 'src', 'lib', 'landing', 'ndaText.generated.ts');

const source = fs.readFileSync(templatePath, 'utf-8');
const result = buildNdaText(source, SAMPLE_DEAL);

const out = `/**
 * AUTO-GENERATED by scripts/generate-landing-nda-text.mjs from templates/professional_mutual_nda_v1.hbs
 * and src/lib/landing/sampleDeal.ts. Do not edit; rerun the script instead.
 */
import type { NdaText } from './ndaText';

export const NDA_TEXT: NdaText = ${JSON.stringify(result)};
`;

fs.writeFileSync(outPath, out);
console.log('Wrote', path.relative(root, outPath));
console.log(result.counts);
console.log(result.variableFieldLabels.join(', '));
